import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const tiers = { 'Fácil': 'easy', 'Médio': 'medium', 'Difícil': 'hard', Brutal: 'brutal' }

async function sentences(level) {
  const markdown = await readFile(resolve(root, `docs/hsk${level}-frases.md`), 'utf8')
  let tier = null
  const rows = []
  for (const line of markdown.split(/\r?\n/)) {
    const heading = line.match(/^#{2,3}\s+(.+)/)
    if (heading) {
      tier = tiers[heading[1]] ?? tier
      continue
    }
    const row = line.match(/^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|/)
    if (!row || !tier || row[1] === 'Chinês' || row[1] === '---') continue
    rows.push({ difficulty: tier, translation: row[2].trim() })
  }
  return rows
}

function sql(value) { return `'${value.replaceAll("'", "''")}'` }

const source = [
  ...(await sentences(1)).map((entry) => ({ ...entry, level: '1' })),
  ...(await sentences(2)).map((entry) => ({ ...entry, level: '2' })),
]
const occurrences = new Map()
const statements = source.map((entry) => {
  const key = `${entry.level}-${entry.difficulty}`
  const ordinal = (occurrences.get(key) ?? 0) + 1
  occurrences.set(key, ordinal)
  const id = `hsk${entry.level}-curated-${entry.difficulty}-${String(ordinal).padStart(3, '0')}`
  return `UPDATE chinese_sentences SET mission = ${sql(`Monte: ${entry.translation}`)}, updated_at = CURRENT_TIMESTAMP WHERE id = ${sql(id)} AND mission IS NULL;`
})

const output = `-- Generated by scripts/generate-chinese-sentence-missions.mjs. Do not edit manually.\n-- Direct player-facing missions for the curated HSK sentence catalogue.\n\n${statements.join('\n')}\n`
await writeFile(resolve(root, 'migrations-chinese/0006_add_curated_sentence_missions.sql'), output, 'utf8')
console.log(`Generated ${statements.length} curated sentence missions.`)
