import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const punctuation = new Set(['。', '？', '！', '，', '、'])
const tiers = { 'Fácil': 'easy', 'Médio': 'medium', 'Difícil': 'hard', Brutal: 'brutal' }

async function vocabulary(level) {
  const csv = await readFile(resolve(root, `files/vocabulario hsk/hsk${level}.txt`), 'utf8')
  return csv.split(/\r?\n/).slice(1).map((line) => line.split(',')[0].trim()).filter(Boolean)
}

function tokenize(sentence, words) {
  const compact = [...sentence].filter((character) => !punctuation.has(character)).join('')
  const tokens = []
  for (let index = 0; index < compact.length;) {
    const word = words.find((candidate) => compact.startsWith(candidate, index))
    if (!word) throw new Error(`Sem token para “${compact.slice(index)}” em “${sentence}”`)
    tokens.push(word)
    index += word.length
  }
  const end = [...sentence].findLast((character) => punctuation.has(character))
  return end ? [...tokens, end] : tokens
}

async function sentences(level) {
  const markdown = await readFile(resolve(root, `docs/hsk${level}-frases.md`), 'utf8')
  let tier = null
  const rows = []
  for (const line of markdown.split(/\r?\n/)) {
    const heading = line.match(/^#{2,3}\s+(.+)/)
    if (heading) {
      tier = tiers[heading[1]] ?? tier
      continue
    }
    const row = line.match(/^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|/)
    if (!row || !tier || row[1] === 'Chinês' || row[1] === '---') continue
    rows.push({ chinese: row[1].trim(), translation: row[2].trim(), difficulty: tier })
  }
  return rows
}

function sql(value) { return `'${value.replaceAll("'", "''")}'` }

const source = [
  ...(await sentences(1)).map((entry) => ({ ...entry, level: '1' })),
  ...(await sentences(2)).map((entry) => ({ ...entry, level: '2' })),
]
const words = [...new Set([...(await vocabulary(1)), ...(await vocabulary(2))])].sort((left, right) => right.length - left.length)
const occurrences = new Map()
const rows = source.map((entry, index) => {
  const key = `${entry.level}-${entry.difficulty}`
  const ordinal = (occurrences.get(key) ?? 0) + 1
  occurrences.set(key, ordinal)
  const id = `hsk${entry.level}-curated-${entry.difficulty}-${String(ordinal).padStart(3, '0')}`
  const tokens = JSON.stringify(tokenize(entry.chinese, words))
  return `  (${sql(id)}, ${sql(entry.level)}, ${sql(entry.difficulty)}, ${sql(tokens)}, ${sql(entry.translation)}, NULL, NULL, NULL, 'active', ${1000 + index}, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)`
})

const output = `-- Generated by scripts/generate-chinese-sentence-catalog.mjs. Do not edit manually.\n-- Source: docs/hsk1-frases.md and docs/hsk2-frases.md.\n\nINSERT OR IGNORE INTO chinese_sentences (id, hsk_level, difficulty, tokens_json, translation, form, mission, opportunity, status, position, created_at, updated_at) VALUES\n${rows.join(',\n')};\n`
await writeFile(resolve(root, 'migrations-chinese/0005_seed_curated_sentences.sql'), output, 'utf8')
console.log(`Generated ${rows.length} curated sentences.`)
